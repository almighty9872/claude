// Regenerates data/anadolu-harita-sekli.js: the outline of Turkey (and the neighbouring land,
// merged into one shape with no borders) for the Anatolian Roots map, from Natural Earth
// 1:10m (public domain, via the world-atlas package), simplified and Mercator-projected, plus
// the natural lakes from Natural Earth's 1:10m lakes layer (ne_10m_lakes.geojson, saved next
// to this script). Only needed if the map's frame or detail should change; the build does not run it.
//   npm install world-atlas@2 topojson-client@3 topojson-server@3 topojson-simplify@3 d3-geo@3
//   curl -o tools/ne_10m_lakes.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_lakes.geojson
//   node tools/anadolu-harita-sekli.mjs
import fs from 'fs';
import { createRequire } from 'module';
import * as topojson from 'topojson-client';
import { topology } from 'topojson-server';
import { presimplify, simplify } from 'topojson-simplify';
import { geoMercator, geoPath, geoBounds } from 'd3-geo';

const require = createRequire(import.meta.url);
const topo = simplify(presimplify(require('world-atlas/countries-10m.json')), 0.0005);
const geoms = topo.objects.countries.geometries;
const bbox = { w: 25.0, e: 45.3, s: 34.3, n: 43.2 };
const NEIGHBOURS = new Set(['Greece', 'Bulgaria', 'Georgia', 'Armenia', 'Azerbaijan', 'Iran', 'Iraq', 'Syria',
  'Lebanon', 'Cyprus', 'N. Cyprus', 'Dhekelia', 'Akrotiri', 'Cyprus U.N. Buffer Zone']);
const turkey = topojson.feature(topo, geoms.find((g) => g.id === '792'));
const land = topojson.merge(topo, geoms.filter((g) => NEIGHBOURS.has(g.properties.name)));
// Natural lakes only: the modern dam reservoirs would look out of place on a map of ancient sites.
const lakesAll = JSON.parse(fs.readFileSync(new URL('./ne_10m_lakes.geojson', import.meta.url), 'utf8'));
const lakesIn = lakesAll.features.filter((f) => {
  const [[w, s], [e, n]] = geoBounds(f);
  return f.properties.featurecla !== 'Reservoir' && !(e < bbox.w || w > bbox.e || n < bbox.s || s > bbox.n);
});
const lakeTopo = simplify(presimplify(topology({ lakes: { type: 'FeatureCollection', features: lakesIn } })), 0.00002);
const lakes = topojson.merge(lakeTopo, lakeTopo.objects.lakes.geometries);

// d3 wants a clockwise ring for a small polygon; the other winding would mean "the whole globe but this".
const frame = { type: 'Polygon', coordinates: [[[bbox.w, bbox.s], [bbox.w, bbox.n], [bbox.e, bbox.n], [bbox.e, bbox.s], [bbox.w, bbox.s]]] };
const W = 1000;
const proj = geoMercator().fitWidth(W, frame);
const [[x0, y0], [, y1]] = geoPath(proj).bounds(frame);
const H = Math.round(y1 - y0);
proj.translate([proj.translate()[0] - x0, proj.translate()[1] - y0]).clipExtent([[0, 0], [W, H]]);
const path = geoPath(proj).digits(1);

// build.ps1 places each site with the same projection: x = tx + k*lon, y = ty - k*ln(tan(pi/4 + lat/2)), angles in radians.
const shape = { W, H, k: +proj.scale().toFixed(4), tx: +proj.translate()[0].toFixed(3), ty: +proj.translate()[1].toFixed(3), land: path(land), turkey: path(turkey), lakes: path(lakes) };
const header = `/* =====================================================================
 * EN: Outline of Turkey, its neighbours and the larger natural lakes for
 *     the Anatolian Roots map (data/anadolu-haritasi.js). Generated by
 *     tools/anadolu-harita-sekli.mjs from Natural Earth 1:10m (public
 *     domain); do not edit by hand.
 * TR: Anadolu haritasinin cizimi. Elle duzenlemeyin; tools/
 *     anadolu-harita-sekli.mjs ile yeniden uretilir.
 * ===================================================================== */
`;
fs.writeFileSync(new URL('../data/anadolu-harita-sekli.js', import.meta.url), `${header}window.ANATOLIA_MAP_SHAPE = /*JSON-START*/${JSON.stringify(shape)}/*JSON-END*/;\n`);
console.log(`W ${W} H ${H}, turkey ${shape.turkey.length} chars, land ${shape.land.length} chars, lakes ${shape.lakes.length} chars (${lakesIn.map((f) => f.properties.name).join(', ')})`);
