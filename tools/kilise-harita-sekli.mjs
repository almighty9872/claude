// Regenerates data/kilise-harita-sekli.js: the Marmara coast in full Natural Earth 1:10m detail
// (public domain, via the world-atlas package), so the Kilise Bul map can zoom into Istanbul and
// still show the Bosphorus between its European and Asian sides. It uses the very projection of
// data/anadolu-harita-sekli.js (the whole-country outline both maps share), so the two line up.
// Only needed if the detail should change; the build does not run it.
//   npm install world-atlas@2 topojson-client@3 d3-geo@3
//   node tools/kilise-harita-sekli.mjs
import fs from 'fs';
import { createRequire } from 'module';
import * as topojson from 'topojson-client';
import { geoMercator, geoPath, geoClipRectangle } from 'd3-geo';

const require = createRequire(import.meta.url);
const topo = require('world-atlas/countries-10m.json');
const geoms = topo.objects.countries.geometries;
const land = topojson.feature(topo, geoms.find((g) => g.id === '792'));

// the same frame and projection as tools/anadolu-harita-sekli.mjs
const bbox = { w: 25.0, e: 45.3, s: 34.3, n: 43.2 };
const frame = { type: 'Polygon', coordinates: [[[bbox.w, bbox.s], [bbox.w, bbox.n], [bbox.e, bbox.n], [bbox.e, bbox.s], [bbox.w, bbox.s]]] };
const W = 1000;
const proj = geoMercator().fitWidth(W, frame);
const [[x0, y0]] = geoPath(proj).bounds(frame);
proj.translate([proj.translate()[0] - x0, proj.translate()[1] - y0]);
// only the Marmara region is drawn in full detail
const [cx0, cy0] = proj([26.0, 41.75]), [cx1, cy1] = proj([30.6, 39.85]);
const path = geoPath({ stream: (s) => proj.stream(geoClipRectangle(cx0, cy0, cx1, cy1)(s)) }).digits(2);
const shape = { box: [+cx0.toFixed(2), +cy0.toFixed(2), +cx1.toFixed(2), +cy1.toFixed(2)], marmara: path(land) };
const header = `/* =====================================================================
 * EN: The Marmara coast in full detail for the Kilise Bul map (Istanbul's two
 *     sides and the Bosphorus). Generated by tools/kilise-harita-sekli.mjs
 *     from Natural Earth 1:10m (public domain); do not edit by hand.
 * TR: Kilise Bul haritasinin Marmara cizimi. Elle duzenlemeyin.
 * ===================================================================== */
`;
fs.writeFileSync(new URL('../data/kilise-harita-sekli.js', import.meta.url), `${header}window.CHURCH_MAP_SHAPE = /*JSON-START*/${JSON.stringify(shape)}/*JSON-END*/;\n`);
console.log('box', shape.box, 'marmara', shape.marmara.length, 'chars');
